import Foundation
import VibeApplication

/// The public prices of the models, kept beside the session store (#574):
///
/// ```
/// Prices/                  0700
///   model-prices.json      0600, { "version": 1, "fetchedAt": …, "prices": {…} }
/// ```
///
/// Written whole, atomically: a fetch that fails never leaves half a list.
public actor FileModelPriceStore: ModelPriceStore {
  private let url: URL

  public init(directory: URL) {
    self.url = directory.appendingPathComponent("model-prices.json", isDirectory: false)
  }

  public func load() async -> ModelPriceList? {
    guard let data = try? Data(contentsOf: url) else { return nil }
    return Self.decode(data)
  }

  public func save(_ list: ModelPriceList) async throws {
    let encoder = JSONEncoder()
    encoder.dateEncodingStrategy = .iso8601
    encoder.outputFormatting = [.sortedKeys]
    try AtomicFileWriter.write(try encoder.encode(list), to: url)
  }

  /// A list in the format kept on disk, `nil` when it is not one this build reads.
  static func decode(_ data: Data) -> ModelPriceList? {
    let decoder = JSONDecoder()
    decoder.dateDecodingStrategy = .iso8601
    guard let list = try? decoder.decode(ModelPriceList.self, from: data),
      list.version == ModelPriceList.currentVersion, !list.prices.isEmpty
    else { return nil }
    return list
  }

  /// The copy shipped with the application, for a first launch offline. Generated by
  /// `Scripts/update-model-prices.sh` before each release.
  public static func bundled() -> ModelPriceList? {
    guard let url = Bundle.module.url(forResource: "model-prices", withExtension: "json"),
      let data = try? Data(contentsOf: url)
    else { return nil }
    return decode(data)
  }
}

/// Fetches LiteLLM's public list of prices with a plain `GET`: no cookie, no cache, a generic
/// `User-Agent`, nothing about the user.
public struct URLSessionModelPriceFetcher: ModelPriceFetching {
  public static let source = URL(
    string:
      "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
  )!
  /// The list weighs about 5 MB and grows; an answer much larger is not it.
  static let maximumSize = 32 * 1024 * 1024

  private let url: URL

  public init(url: URL = URLSessionModelPriceFetcher.source) {
    self.url = url
  }

  public func fetchPriceList() async throws -> Data {
    let configuration = URLSessionConfiguration.ephemeral
    configuration.httpCookieStorage = nil
    configuration.httpShouldSetCookies = false
    configuration.urlCache = nil
    configuration.timeoutIntervalForRequest = 15
    configuration.timeoutIntervalForResource = 15
    let session = URLSession(configuration: configuration)
    defer { session.finishTasksAndInvalidate() }
    var request = URLRequest(url: url, cachePolicy: .reloadIgnoringLocalCacheData)
    request.httpMethod = "GET"
    request.setValue("VibeManager", forHTTPHeaderField: "User-Agent")
    let (data, response) = try await session.data(for: request)
    guard (response as? HTTPURLResponse)?.statusCode == 200,
      response.expectedContentLength <= Int64(Self.maximumSize), data.count <= Self.maximumSize
    else { throw ModelPriceListError.unexpectedResponse }
    return data
  }
}
